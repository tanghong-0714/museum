test('refining one direction preserves the prior model source and deduplicates the paid request',async()=>{
 const f=await fixture(),j=await f.views.create(f.input);await f.views.waitForIdle();
 const before=await f.views.asset(j.id,'left'),req={requestId:randomUUID(),views:['left']};
 const refined=await f.views.refine(j.id,req);await f.views.waitForIdle();
 assert.notEqual(refined.id,j.id);assert.equal(f.calls.length,5);
 assert.deepEqual((await f.views.asset(j.id,'left')).content,before.content);
 assert.notDeepEqual((await f.views.asset(refined.id,'left')).content,before.content);
 assert.deepEqual((await f.views.asset(refined.id,'top')).content,(await f.views.asset(j.id,'top')).content);
 assert.equal((await f.views.refine(j.id,req)).id,refined.id);assert.equal(f.calls.length,5);
 await assert.rejects(f.views.refine(j.id,{requestId:randomUUID(),views:['front']}),{status:400});
});
